# 地区切换可选地域（A+C 方案）：code 为空表示「全国（不过滤）」；
# 选中某市后按「本市 → 本省（仅省） → 全国」梯度召回（见 region_matches）。
REGION_OPTIONS: List[Dict[str, str]] = [
    {"code": "", "name": "全国（全部）"},
    {"code": "芜湖市", "name": "芜湖市"},
    {"code": "合肥市", "name": "合肥市"},
    {"code": "马鞍山市", "name": "马鞍山市"},
    {"code": "蚌埠市", "name": "蚌埠市"},
]


def region_matches(jurisdiction: List[str], region: str) -> bool:
    """地区切换过滤（A+C 方案核心）。

    选中某市（如「合肥市」）时，召回范围按梯度展开：
    - 本市文件（jurisdiction 含该市）              → 直接命中
    - 全国文件（jurisdiction 含「全国」）          → 上位法，纳入
    - 本省文件（jurisdiction 仅含省、不含其它市） → 上位法，纳入
    - 其它市文件（即便同省）                       → 排除

    关键：省级文件 jurisdiction 仅 [省份]，而某市文件为 [省份, 市]；
    因此不能简单用「省」做交集（会把同省其它市文件也带进来），必须区分
    「仅省」与「省+市」，只对「仅省」的省级上位法放行。
    """
    if not region:
        return True
    j = set(jurisdiction or [])
    if region in j:
        return True
    if "全国" in j:
        return True
    province = CITY_PROVINCE.get(region)
    if province and province in j:
        # 仅含省、不含任何市 → 省级上位法；含其它市 → 视为它市文件，排除
        cities = {x for x in j if x in CITY_PROVINCE}
        if not cities:
            return True
    return False

